#[allow(unused_variables)]
fn main() {
    input! {
        S: Chars,
    }
    let mut counter = BTreeMap::new();
    for &c in &S {
        *counter.entry(c).or_insert(0) += 1;
    }
    let mut c = '.';
    for (&d, &v) in counter.iter() {
        if v == 1 {
            c = d;
        }
    }
    for i in 0..S.len() {
        if S[i] == c {
            println!("{}", i + 1);
        }
    }
}

